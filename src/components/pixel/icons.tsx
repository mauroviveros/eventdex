export type IconName = keyof typeof ICONS;

const pathOf = (rows: readonly string[]) =>
  rows
    .flatMap((row, y) =>
      [...row].map((c, x) => (c === "#" ? `M${x} ${y}h1v1h-1z` : "")),
    )
    .join("");

export function PixelIcon({
  name,
  size = 16,
}: {
  name: IconName;
  size?: number;
}) {
  return (
    <svg
      aria-hidden
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      fill="currentColor"
      className="shrink-0"
    >
      <path d={pathOf(ICONS[name])} />
    </svg>
  );
}
